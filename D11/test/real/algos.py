#!/usr/bin/env python3
"""Assemble test/real/algos.asm with b43-asm and write emulator cases (D11EmuTest format): random
inputs in shared memory, expected results computed here.
  algos.py <outdir>      writes <outdir>/algos.bin and <outdir>/algos-cases.txt"""
import os, random, struct, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1]
os.makedirs(out, exist_ok=True)
subprocess.run([os.environ.get('B43ASM', 'b43-asm'), os.path.join(here, 'algos.asm'), out + '/algos.bin', '-f', 'raw-le32'], check=True)
data = open(out + '/algos.bin', 'rb').read()
words = [struct.unpack('<Q', data[8 * i:8 * i + 8])[0] for i in range(len(data) // 8)]
done = len(words) - 1

def crc16(ws):
    crc = 0xffff
    for w in ws:
        crc ^= w
        for _ in range(16):
            crc = ((crc << 1) ^ 0x1021) & 0xffff if crc & 0x8000 else (crc << 1) & 0xffff
    return crc

def chunks(addr, ws):
    res = []
    for i in range(0, len(ws), 4):
        part = ws[i:i + 4]
        res.append(('shm:%x/%d' % (addr + i, 2 * len(part)), int.from_bytes(b''.join(struct.pack('<H', x) for x in part), 'little')))
    return res

rnd = random.Random(20261027)
vectors = [('random1', [rnd.randrange(65536) for _ in range(16)], [rnd.randrange(65536) for _ in range(8)]),
           ('random2', [rnd.randrange(65536) for _ in range(16)], [rnd.randrange(65536) for _ in range(8)]),
           ('zeros', [0] * 16, [0] * 8),
           ('ones', [0xffff] * 16, [0xffff] * 8),
           ('descending', list(range(16, 0, -1)), [8000 - 1000 * i for i in range(8)]),
           ('sorted', list(range(16)), list(range(8)))]
with open(out + '/algos-cases.txt', 'w') as f:
    f.write('# generated by test/real/algos.py; do not edit\n')
    for name, data16, sortin in vectors:
        f.write('case algos_%s\ncode %s\nend %x\nsteps 200000\n' % (name, ' '.join('%016x' % w for w in words), done))
        for k, v in chunks(0, data16) + chunks(0x40, sortin):
            f.write('set %s 0x%x\n' % (k, v))
        exp = [('shm:80/2', sum(data16) & 0xffff), ('shm:81/2', __import__('functools').reduce(lambda a, b: a ^ b, data16)),
               ('shm:82/2', crc16(data16))] + chunks(0x40, sorted(sortin))
        for k, v in exp:
            f.write('expect %s 0x%x\n' % (k, v))
        f.write('end\n')
print(len(words), 'instructions; done at', done)
